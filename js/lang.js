function initLanguage() {
  const currentLang = localStorage.getItem('lang') || 'es'; // default Spanish
  
  const els = document.querySelectorAll('[data-i18n], [data-i18n-title], [data-i18n-href]');
  
  function applyLang(lang) {
    els.forEach(el => {
      if (el.hasAttribute('data-i18n')) {
        const key = el.getAttribute('data-i18n');
        if (dictionary[key] && dictionary[key][lang]) {
          if (el.tagName.toLowerCase() === 'input' || el.tagName.toLowerCase() === 'textarea') {
            el.setAttribute('placeholder', dictionary[key][lang]);
          } else if (key === 'whatsapp-float-txt') {
            // Rebuild letter spans for CSS animation
            const text = dictionary[key][lang];
            let html = '';
            for (let i = 0; i < text.length; i++) {
              const char = text[i] === ' ' ? '&nbsp;' : text[i];
              html += `<span class="cita-letter">${char}</span>`;
            }
            el.innerHTML = html;
          } else {
            el.innerHTML = dictionary[key][lang];
          }
        }
      }
      
      if (el.hasAttribute('data-i18n-title')) {
        const key = el.getAttribute('data-i18n-title');
        if (dictionary[key] && dictionary[key][lang]) {
          el.setAttribute('title', dictionary[key][lang]);
          el.setAttribute('aria-label', dictionary[key][lang]);
        }
      }

      if (el.hasAttribute('data-i18n-href')) {
        const key = el.getAttribute('data-i18n-href');
        if (dictionary[key] && dictionary[key][lang]) {
          el.setAttribute('href', dictionary[key][lang]);
        }
      }
    });
    
    document.title = dictionary["page_title"][lang];
    document.documentElement.lang = lang;
    
    // Update active class on toggles
    document.querySelectorAll('.lang-toggle-checkbox').forEach(cbx => {
      // If language is CA, checkbox is checked. If ES, unchecked.
      cbx.checked = (lang === 'ca');
    });

    // Handle legal text translation
    window.dispatchEvent(new CustomEvent('languageChanged', { detail: { lang } }));
  }

  // Bind clicks
  document.querySelectorAll('.lang-toggle-checkbox').forEach(cbx => {
    cbx.addEventListener('change', (e) => {
      const selectedLang = e.target.checked ? 'ca' : 'es';
      localStorage.setItem('lang', selectedLang);
      applyLang(selectedLang);
    });
  });

  // Apply initially
  applyLang(currentLang);
}

document.addEventListener('DOMContentLoaded', initLanguage);
